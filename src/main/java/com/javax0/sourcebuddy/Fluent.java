package com.javax0.sourcebuddy;

import java.io.IOException;
import java.io.InputStream;
import java.lang.invoke.MethodHandles;
import java.nio.charset.Charset;
import java.nio.file.Path;
import java.util.stream.Stream;

/**
 * Defines the fluent API for the SourceBuddy Java runtime compiler.
 *
 * <p>The interface is not meant to be implemented directly. Instead, start with
 * {@link Compiler#java()} and chain method calls through the nested interfaces.
 * The typical flow is:
 *
 * <pre>{@code
 * var loaded = Compiler.java()
 *     .from("com.example.Foo", "public class Foo { ... }")
 *     .compile()
 *     .load();
 * Class<?> fooClass = loaded.get("com.example.Foo");
 * }</pre>
 *
 * <p>The nested interfaces model the states of the fluent builder:
 * {@link AddSource} → {@link CanIsolate} → {@link Compiled} → {@link Compiler.Loaded}.
 */
@SuppressWarnings("unused")
public interface Fluent {

    /**
     * The initial state of the fluent API. Methods on this interface add source files or
     * configure the compiler before compilation begins.
     *
     * <p>After adding at least one source, the builder transitions to {@link CanIsolate},
     * which exposes the {@link CanIsolate#compile(String...) compile()} method.
     */
    interface AddSource {

        /**
         * Returns {@code true} if at least one source has been added and the compiler
         * is ready to compile.
         *
         * @return {@code true} if compilation can proceed
         */
        boolean canCompile();

        /**
         * Adds an already-compiled class from a raw byte array, bypassing the Java compiler.
         * Useful for loading pre-compiled or externally generated bytecode.
         *
         * @param code the raw class bytecode
         * @return the {@link Compiled} state
         * @throws IOException if the byte array cannot be processed
         */
        Compiled byteCode(byte[] code) throws IOException;

        /**
         * Adds an already-compiled class by reading bytecode from an {@link InputStream}.
         *
         * @param is the stream to read the class bytecode from; the stream is fully consumed
         * @return the {@link Compiled} state
         * @throws IOException if the stream cannot be read
         */
        Compiled byteCode(InputStream is) throws IOException;

        /**
         * Adds an already-compiled class by reading a {@code .class} file from the filesystem.
         *
         * @param classpath path to the {@code .class} file
         * @return the {@link Compiled} state
         * @throws IOException if the file cannot be read
         */
        Compiled byteCode(Path classpath) throws IOException;

        /**
         * Adds all Java source files found under the given directory, inferring the class
         * names from the file structure.
         *
         * @param path root directory to scan for {@code .java} files
         * @return the next builder state, allowing class-loading options to be specified
         * @throws IOException            if the directory cannot be read
         * @throws ClassNotFoundException if a class name cannot be inferred from the file
         */
        SpecifyNestHiddenNamed from(Path path) throws IOException, ClassNotFoundException;

        /**
         * Adds a single Java source file with an explicit binary class name.
         * Use this overload when the file location does not match the package structure.
         *
         * @param binary the fully qualified binary class name (e.g. {@code "com.example.Foo"})
         * @param path   path to the {@code .java} source file
         * @return the next builder state
         */
        SpecifyNestHiddenNamed from(String binary, Path path);

        /**
         * Adds a single Java source provided as a string with an explicit class name.
         *
         * @param name   the fully qualified binary class name (e.g. {@code "com.example.Foo"})
         * @param source the Java source code
         * @return the next builder state
         */
        SpecifyNestHiddenNamed from(String name, String source);

        /**
         * Adds a single Java source provided as a string, inferring the class name from
         * the {@code package} and {@code class} declarations in the source.
         *
         * @param source the Java source code; must contain a recognisable class declaration
         * @return the next builder state
         * @throws ClassNotFoundException if the class name cannot be inferred from the source
         */
        SpecifyNestHiddenNamed from(String source) throws ClassNotFoundException;

        /**
         * Resets the compiler to its initial state, discarding all added sources and options.
         * Useful for reusing the same compiler instance for multiple independent compilations.
         *
         * @return this builder in its initial state
         */
        AddSource reset();

        /**
         * Passes raw compiler options directly to {@code javac}.
         * Prefer the typed option methods (e.g. {@link #release(int)}, {@link #encoding(Charset)})
         * where available.
         *
         * @param options raw {@code javac} command-line options
         * @return the next builder state
         */
        CanIsolate options(String... options);


        // snippet CompilerOptions
        /**
         * Sets the {@code --release} version passed to {@code javac}, controlling both the
         * source language level and the minimum JVM version the output must run on.
         *
         * @param version the Java release version (e.g. {@code 21})
         * @return the next builder state
         */
        CanIsolate release(int version);
        // * `release(int)` sets the release version of the Java compiler.

        /**
         * Sets the {@code -source} version passed to {@code javac}, controlling which Java
         * language features are accepted in the source code.
         *
         * @param version the source compatibility version (e.g. {@code 21})
         * @return the next builder state
         */
        CanIsolate source(int version);
        // * `source(int)` sets the source version of the Java compiler.

        /**
         * Sets the {@code -target} version passed to {@code javac}, controlling the minimum
         * JVM version that the generated class files must be compatible with.
         *
         * @param version the target compatibility version (e.g. {@code 21})
         * @return the next builder state
         */
        CanIsolate target(int version);
        // * `target(int)` sets the target version of the Java compiler.

        /**
         * Sets the character encoding used to read the source files.
         *
         * @param charset the charset (e.g. {@link java.nio.charset.StandardCharsets#UTF_8})
         * @return the next builder state
         */
        CanIsolate encoding(Charset charset);
        // * `encoding(Charset)` sets the encoding of the source files.

        /**
         * Enables verbose output from {@code javac}, printing details about each class
         * being compiled and each class file being loaded.
         *
         * @return the next builder state
         */
        CanIsolate verbose();
        // * `verbose()` sets the compiler to be verbose.

        /**
         * Sets the level of debug information emitted into the class files.
         * Corresponds to the {@code -g} / {@code -g:} family of {@code javac} flags.
         *
         * @param debugInfo the desired level; {@code null} or {@link DebugInfo#ALL} emits
         *                  all debug information ({@code -g})
         * @return the next builder state
         * @see DebugInfo
         */
        CanIsolate debugInfo(DebugInfo debugInfo);
        // * `debugInfo(DebugInfo)` sets the debug information level of the compiler.
        // The possible values are `NONE`, `LINES`, `SOURCE`, `VARS`, and `ALL` as listed in the enumeration.

        /**
         * Suppresses all debug information in the generated class files ({@code -g:none}).
         *
         * @return the next builder state
         */
        CanIsolate noDebugInfo();
        // * `noDebugInfo()` sets the compiler to suppress debug information.

        /**
         * Suppresses all compiler warnings ({@code -nowarn}).
         *
         * @return the next builder state
         */
        CanIsolate nowarn();
        // * `nowarn()` sets the compiler to suppress warnings.

        /**
         * Enables deprecation warnings for uses of deprecated APIs ({@code -deprecation}).
         *
         * @return the next builder state
         */
        CanIsolate showDeprecation();
        // * `showDeprecation()` sets the compiler to show deprecation warnings.

        /**
         * Stores formal parameter names in the generated class files ({@code -parameters}),
         * making them accessible at runtime via reflection.
         *
         * @return the next builder state
         */
        CanIsolate parameters();
        // * `parameters()` sets the compiler to store formal parameter names of constructors and methods in the generated class files.

        /**
         * Represents a {@code --add-exports} directive passed to the compiler, controlling
         * which module packages are visible during compilation.
         *
         * <p>Build an instance using the fluent factory:
         * <pre>{@code
         * Export.from("java.base").thePackage("sun.nio.ch").to("com.example")
         * }</pre>
         */
        class Export {
            final String module;
            final String pckg;
            final String otherModule;

            /**
             * Creates an {@code Export} directive.
             *
             * @param module      the module whose package is being exported
             * @param pckg        the package to export, or {@code "*"} for all packages
             * @param otherModule the target module, or {@code "ALL-UNNAMED"} for unnamed modules
             */
            public Export(String module, String pckg, String otherModule) {
                this.module = module;
                this.pckg = pckg;
                this.otherModule = otherModule;
            }

            /**
             * Starts building an {@code Export} for the given module. The package defaults to
             * {@code "*"} (all packages) and the target defaults to {@code "ALL-UNNAMED"}.
             *
             * @param module the module whose package will be exported
             * @return a new {@code Export} instance
             */
            public static Export from(String module) {
                return new Export(module, "*", "ALL-UNNAMED");
            }

            /**
             * Narrows this export to a specific package.
             *
             * @param pckg the package name to export
             * @return a new {@code Export} with the package set
             */
            public Export thePackage(String pckg) {
                return new Export(module, pckg, otherModule);
            }

            /**
             * Targets this export at a specific module.
             *
             * @param otherModule the module that should receive the export
             * @return a new {@code Export} with the target module set
             */
            public Export to(String otherModule) {
                return new Export(module, pckg, otherModule);
            }

            /**
             * Returns the export directive in the format expected by {@code javac}:
             * {@code module/package=targetModule}.
             *
             * @return the formatted {@code --add-exports} value
             */
            public String toString() {
                return module + "/" + pckg + "=" + otherModule;
            }
        }

        /**
         * Adds one or more {@code --add-exports} directives to the compiler invocation,
         * making otherwise inaccessible module packages visible during compilation.
         *
         * <p>Example:
         * <pre>{@code
         * addExports(Export.from("java.base").thePackage("sun.nio.ch").to("ALL-UNNAMED"))
         * }</pre>
         *
         * @param exports the export directives to add
         * @return the next builder state
         * @see Export
         */
        CanIsolate addExports(Export... exports);
        // * `addExports(Export...)` adds export directives to the module declaration.
        // To create an `Export` object, use the methods of the class `Export`.
        // A typical usage is
        // +
        // [source,java]
        // ----
        //             addExports(Export.from("module").thePackage("package").to("otherModule"))
        // ----
        // +
        // You can make a static import for the method `from` to make the code more readable.

        /**
         * Adds modules to the set of root modules to resolve ({@code --add-modules}),
         * making them available on the module path during compilation.
         *
         * @param modules the module names to add
         * @return the next builder state
         */
        CanIsolate addModules(String... modules);
        // * `addModules(String...)` adds required modules to the module declaration.

        /**
         * Restricts the set of observable modules ({@code --limit-modules}), preventing
         * modules not in the list from being resolved during compilation.
         *
         * @param modules the module names to allow
         * @return the next builder state
         */
        CanIsolate limitModules(String... modules);
        // * `limitModules(String...)` limits the modules that are visible during compilation.

        /**
         * Sets the module name for the compiled sources ({@code --module}), used when
         * compiling a full module rather than individual source files.
         *
         * @param module the module name
         * @return the next builder state
         */
        CanIsolate module(String module);
        // * `module(String)` sets the module name of the compiled classes.

        // end snippet

        /**
         * Appends entries to the class path used during compilation ({@code --class-path}).
         *
         * @param cp the class-path string, using the platform path separator
         * @return the next builder state
         */
        CanIsolate classPath(final String cp);

        /**
         * Adds the class path of the currently running JVM to the compiler's class path,
         * making all classes already visible at runtime also visible during compilation.
         *
         * @return the next builder state
         */
        CanIsolate inheritClassPath();

        /**
         * Adds the system (boot) class path to the compiler's class path.
         *
         * @return the next builder state
         */
        CanIsolate systemClassPath();

        /**
         * Restricts compilation to the source files whose classes carry specific annotations.
         * Only classes annotated with the given annotation type names will be compiled.
         *
         * @param options fully qualified annotation type names
         * @return the next builder state
         */
        CanIsolate annotatedClasses(String... options);

        /**
         * Adds named modules to the module graph used during compilation and class loading.
         *
         * @param modules the module names to include
         * @return this builder, allowing further sources or options to be added
         */
        AddSource modules(String... modules);
    }

    /**
     * Builder state reached after at least one source or option has been provided.
     * Extends {@link AddSource} and adds the ability to compile and optionally isolate
     * the compilation in a separate class loader.
     */
    interface CanIsolate extends AddSource {

        /**
         * Compiles all added sources using the configured options.
         *
         * @param options additional raw {@code javac} options applied only to this invocation
         * @return the {@link Compiled} state, giving access to the resulting bytecode
         * @throws Compiler.CompileException if {@code javac} reports compilation errors;
         *                                   the exception message contains the compiler output
         */
        Compiled compile(String... options) throws Compiler.CompileException;

        /**
         * Isolates the compilation in a dedicated class loader, preventing compiled classes
         * from being visible to the parent class loader. Useful when compiling classes that
         * must not conflict with existing classes on the application class path.
         *
         * @return the next builder state with isolation enabled
         */
        CanCompile isolate();
    }

    /**
     * Builder state where the compilation context has been isolated. Inherits all
     * options from {@link CanIsolate} and additionally enforces that compiled classes
     * are loaded in their own class loader.
     */
    interface CanCompile extends CanIsolate {

        /**
         * Compiles all added sources in the isolated class loader context.
         *
         * @param options additional raw {@code javac} options applied only to this invocation
         * @return the {@link Compiled} state
         * @throws Compiler.CompileException if {@code javac} reports compilation errors
         */
        Compiled compile(String... options) throws Compiler.CompileException;
    }

    /**
     * Builder state reached after a source is added via {@link AddSource#from}.
     * Allows specifying how the compiled class should be defined in the JVM: as a
     * hidden class, a nest member, or a plain named class.
     *
     * <p>If none of the methods here are called, the class is defined as a plain named
     * class (equivalent to calling {@link #named()}).
     */
    interface SpecifyNestHiddenNamed extends CanIsolate {

        /**
         * Defines the compiled class as a <em>hidden class</em> using
         * {@link MethodHandles.Lookup#defineHiddenClass}. Hidden classes are not
         * discoverable by name and are not accessible from other classes.
         *
         * @param classOptions options controlling the hidden class (e.g. nestmate, strong)
         * @return the next builder state
         */
        CanIsolate hidden(MethodHandles.Lookup.ClassOption... classOptions);

        /**
         * Defines the compiled class as a hidden class using the provided {@link MethodHandles.Lookup},
         * which determines the access context of the hidden class.
         *
         * @param lookup       the lookup object that defines the access context
         * @param classOptions options controlling the hidden class
         * @return the next builder state
         */
        CanIsolate hidden(MethodHandles.Lookup lookup, MethodHandles.Lookup.ClassOption... classOptions);

        /**
         * Defines the compiled class as a <em>nest member</em> hidden class, making it a
         * nestmate of the class represented by the caller's lookup. Nestmates can access each
         * other's private members.
         *
         * @param classOptions options controlling the hidden class
         * @return the next builder state
         */
        CanIsolate nest(MethodHandles.Lookup.ClassOption... classOptions);

        /**
         * Defines the compiled class as a nest member hidden class using the provided lookup.
         *
         * @param lookup       the lookup object representing the nest host
         * @param classOptions options controlling the hidden class
         * @return the next builder state
         */
        CanIsolate nest(MethodHandles.Lookup lookup, MethodHandles.Lookup.ClassOption... classOptions);

        /**
         * Defines the compiled class as a plain named class (the default behaviour),
         * loaded through the standard class loading mechanism. The class will be visible
         * by name to other classes sharing the same class loader.
         *
         * @return the next builder state
         */
        CanIsolate named();

        /**
         * Defines the compiled class as a plain named class using the provided
         * {@link MethodHandles.Lookup} for access-checking purposes.
         *
         * @param lookup the lookup object to use when defining the class
         * @return the next builder state
         */
        CanIsolate named(MethodHandles.Lookup lookup);
    }

    /**
     * Builder state reached after compilation (or direct bytecode loading) succeeds.
     * Provides access to the compiled bytecode and allows the classes to be loaded
     * into the JVM.
     */
    interface Compiled {

        /**
         * Adds an already-compiled class from a raw byte array into the current compiled set.
         *
         * @param code the raw class bytecode
         * @return this {@link Compiled} state
         * @throws IOException if the byte array cannot be processed
         */
        Compiled byteCode(byte[] code) throws IOException;

        /**
         * Adds an already-compiled class by reading bytecode from an {@link InputStream}.
         *
         * @param is the stream to read the class bytecode from
         * @return this {@link Compiled} state
         * @throws IOException if the stream cannot be read
         */
        Compiled byteCode(InputStream is) throws IOException;

        /**
         * Adds an already-compiled class by reading a {@code .class} file from the filesystem.
         *
         * @param classpath path to the {@code .class} file
         * @return this {@link Compiled} state
         * @throws IOException if the file cannot be read
         */
        Compiled byteCode(Path classpath) throws IOException;

        /**
         * Returns a {@link Stream} of raw bytecode arrays for all compiled classes.
         * Useful for inspecting, transforming, or persisting the compiled bytecode.
         *
         * @return a stream of bytecode arrays, one per compiled class
         */
        Stream<byte[]> stream();

        /**
         * Returns the bytecode of the single compiled class.
         * Throws if there is not exactly one compiled class.
         *
         * @return the bytecode of the compiled class
         * @throws ClassNotFoundException if no class has been compiled or more than one class exists
         */
        byte[] get() throws ClassNotFoundException;

        /**
         * Loads all compiled classes into the JVM using a {@link ByteClassLoader}.
         *
         * @param options class loading strategy options:
         *                {@link Compiler.LoaderOption#REVERSE} loads compiled classes before
         *                consulting the parent loader;
         *                {@link Compiler.LoaderOption#SLOPPY} tolerates individual class load
         *                failures instead of aborting
         * @return the {@link Compiler.Loaded} state for accessing the loaded {@link Class} objects
         * @throws ClassNotFoundException if a class cannot be loaded and {@code SLOPPY} was not specified
         */
        Compiler.Loaded load(Compiler.LoaderOption... options) throws ClassNotFoundException;

        /**
         * Saves all compiled class files to the given directory, recreating the package
         * directory structure beneath it.
         *
         * @param path the root directory to write {@code .class} files into
         */
        void saveTo(Path path);

        /**
         * Resets the compiler to its initial state, discarding all compiled bytecode.
         * Use this to begin a new compilation with the same compiler instance.
         *
         * @return this builder in its initial {@link AddSource} state
         */
        AddSource reset();
    }
}
